def text_width(s, spacing=1):
    return sum(len(G[c][0]) + spacing for c in s) - spacing


def draw_text(dst, s, x, y, color, outline=None, shadow=None, spacing=1):
    """Draw text with optional 1px outline (8-neighbour) and drop shadow."""
    w = text_width(s, spacing) + 2
    h = 11
    mask = np.zeros((h, w), bool)
    cx = 1
    for ch in s:
        g = G[ch]
        for yy, row in enumerate(g):
            for xx, c in enumerate(row):
                if c == '#':
                    mask[1 + yy, cx + xx] = True
        cx += len(g[0]) + spacing

    def put(m, col, ox, oy):
        ys, xs = np.nonzero(m)
        for yy, xx in zip(ys, xs):
            X, Y = x - 1 + xx + ox, y - 1 + yy + oy
            if 0 <= X < dst.shape[1] and 0 <= Y < dst.shape[0]:
                dst[Y, X, :3] = col
                dst[Y, X, 3] = 255

    if outline is not None:
        o = np.zeros_like(mask)
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                o |= np.roll(np.roll(mask, dy, 0), dx, 1)
        if shadow is not None:
            put(o, shadow, 0, 1)
        put(o, outline, 0, 0)
    elif shadow is not None:
        put(mask, shadow, 0, 1)
    put(mask, color, 0, 0)
    return text_width(s, spacing)
